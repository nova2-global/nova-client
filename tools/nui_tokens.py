#!/usr/bin/env python3
"""Generate the NovaUI theme style sheet from the design tokens.

    python tools/nui_tokens.py           write tokens.rcss and the token table in
                                         docs/ui/AUTHORING.md, print the contrast report
    python tools/nui_tokens.py --check   write nothing; exit 1 if either output is
                                         stale or a contrast pair fails (for CI and agents)

Input:  assets/nui/nui/theme/tokens.json  {"shared": {...}, "skins": {...}, <palette>: {...}, ...}
        assets/nui/nui/theme/themes.json  the player themes and the body classes each one sets
Output: assets/nui/nui/theme/tokens.rcss  (store path nui/theme/tokens.rcss)

`shared` holds the values every theme starts from and goes into `body { ... }`.
Every other top-level key except `skins` is a palette of colors: palette `p`
goes into `body.theme-p { ... }`. `skins` (optional) holds per-skin tokens:
`skins.s` goes into `body.skin-s { ... }`, where it overrides shared values or
adds tokens of its own, named `s-...`. themes.json names the classes: each
theme puts exactly one `skin-*` and one `theme-*` class on every document's
<body> (NuiRuntime.h). The first theme's palette is also emitted for a plain
`body`, because RmlUi resolves styles once inside LoadDocument, before any
class can be set.

Contrast uses the WCAG 2.x relative luminance formula, per palette.
Translucent colors are composited over the pair's background before measuring.
"""
import json
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TOKENS_JSON = os.path.join(REPO, "assets", "nui", "nui", "theme", "tokens.json")
THEMES_JSON = os.path.join(REPO, "assets", "nui", "nui", "theme", "themes.json")
TOKENS_RCSS = os.path.join(REPO, "assets", "nui", "nui", "theme", "tokens.rcss")
AUTHORING_MD = os.path.join(REPO, "docs", "ui", "AUTHORING.md")
COMMAND = "python tools/nui_tokens.py"

TABLE_BEGIN = "<!-- tokens:begin (generated by tools/nui_tokens.py; do not edit by hand) -->"
TABLE_END = "<!-- tokens:end -->"

# The first theme of themes.json, which CPythonSystem never writes to UI_THEME
# (nova-client-src NuiPaths.h kDefaultThemeId).
DEFAULT_THEME_ID = "modern-dark"
SKINS = "skins"

# Every palette must define these colors (docs/ui/AUTHORING.md explains each role).
REQUIRED_COLORS = (
    "surface", "surface-raised", "surface-sunken", "surface-hover", "border",
    "text", "text-muted", "text-inverse",
    "accent", "accent-hover", "accent-text",
    "danger", "danger-hover", "warning", "success",
    "focus-ring", "selection", "overlay-scrim", "tooltip-bg",
)

REQUIRED_SHARED = (
    "font-family",
    "space-1", "space-2", "space-3", "space-4", "space-5", "space-6",
    "radius-sm", "radius-md", "radius-lg",
    "font-xs", "font-sm", "font-md", "font-lg", "font-xl",
    "dur-fast", "dur-med", "dur-slow",
    "ease-out", "ease-in-out",
)

# Tween names RmlUi 6.3 accepts (Source/Core/PropertyParserAnimation.cpp).
RMLUI_TWEENS = {
    "%s-%s" % (family, mode)
    for family in ("back", "bounce", "circular", "cubic", "elastic", "exponential", "linear",
                   "quadratic", "quartic", "quintic", "sine")
    for mode in ("in", "out", "in-out")
}

# (foreground, background, minimum ratio, what the pair is used for).
# 4.5 is WCAG AA for normal-size text; 3.0 is the AA minimum for UI component
# boundaries and focus indicators.
CONTRAST_PAIRS = (
    ("text", "surface", 4.5, "body text"),
    ("text", "surface-raised", 4.5, "text on panels"),
    ("text", "surface-sunken", 4.5, "text in inputs and slots"),
    ("text", "surface-hover", 4.5, "hovered rows and buttons"),
    ("text", "selection", 4.5, "selected list rows"),
    ("text-muted", "surface", 4.5, "secondary text"),
    ("text-muted", "surface-raised", 4.5, "secondary text on panels"),
    ("text-muted", "surface-sunken", 4.5, "placeholders"),
    ("text-muted", "surface-hover", 4.5, "list row meta on hovered rows"),
    ("text-muted", "selection", 4.5, "list row meta on selected rows"),
    ("accent", "surface", 4.5, "accent text (selected tab)"),
    ("accent", "surface-raised", 4.5, "accent text on panels"),
    ("accent-text", "accent", 4.5, "primary button label"),
    ("accent-text", "accent-hover", 4.5, "hovered primary button label"),
    ("accent-text", "danger", 4.5, "danger button and badge label"),
    ("accent-text", "danger-hover", 4.5, "hovered danger button label"),
    ("accent-text", "success", 4.5, "success badge label"),
    ("accent-text", "warning", 4.5, "warning badge label"),
    ("danger", "surface", 4.5, "error text"),
    ("danger", "surface-raised", 4.5, "error text on panels"),
    ("warning", "surface-raised", 4.5, "warning text on panels"),
    ("success", "surface-raised", 4.5, "success text on panels"),
    ("text-inverse", "tooltip-bg", 4.5, "tooltip text"),
    ("edge-gm", "tooltip-bg", 4.5, "GM names on edge button labels"),
    ("focus-ring", "surface", 3.0, "focus ring"),
    ("focus-ring", "surface-raised", 3.0, "focus ring on panels"),
    ("focus-ring", "surface-sunken", 3.0, "focus ring on inputs"),
    ("focus-ring", "selection", 3.0, "focus ring on a selected list row"),
    ("accent", "surface-sunken", 3.0, "slider fill, checked toggle"),
)

NAME_RE = re.compile(r"^[a-z][a-z0-9-]*$")
COLOR_RE = re.compile(r"^#([0-9a-fA-F]{6}|[0-9a-fA-F]{8})$")
LENGTH_RE = re.compile(r"^-?\d+(\.\d+)?dp$")
DURATION_RE = re.compile(r"^\d+(\.\d+)?s$")
# themes.json, as NuiRuntime's ParseThemes reads it (nova-client-src NuiRuntime.h).
THEME_ID_RE = re.compile(r"^[a-z0-9-]{1,31}$")
THEME_CLASS_RE = re.compile(r"^[a-z][a-z0-9-]{0,62}$")
THEMES_MAX = 16
THEME_CLASSES_MAX = 8
THEME_LABEL_MAX = 64


class TokenError(Exception):
    pass


# --- colors ----------------------------------------------------------------

def parse_color(value):
    """#rrggbb or #rrggbbaa -> (r, g, b, a) as floats in 0..1."""
    if not COLOR_RE.match(value):
        raise TokenError("not a #rrggbb or #rrggbbaa color: %r" % value)
    digits = value[1:]
    channels = [int(digits[i:i + 2], 16) / 255.0 for i in range(0, len(digits), 2)]
    if len(channels) == 3:
        channels.append(1.0)
    return tuple(channels)


def composite(fg, bg):
    """Straight-alpha source over an opaque background."""
    alpha = fg[3]
    return tuple(fg[i] * alpha + bg[i] * (1.0 - alpha) for i in range(3)) + (1.0,)


def relative_luminance(color):
    def linear(c):
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = (linear(c) for c in color[:3])
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast_ratio(fg, bg):
    """WCAG contrast of fg drawn over bg; translucent colors are composited first."""
    if bg[3] < 1.0:
        raise TokenError("a contrast background must be opaque")
    fg = composite(fg, bg)
    lighter, darker = sorted((relative_luminance(fg), relative_luminance(bg)), reverse=True)
    return (lighter + 0.05) / (darker + 0.05)


# --- themes.json -------------------------------------------------------------

def validate_themes(document):
    """The rules of nui/theme/themes.json (the runtime's and lint's), plus the
    content convention: one skin-* and one theme-* class per theme. Returns
    the themes as [(id, label, [classes])] in menu order."""
    if not isinstance(document, dict) or not isinstance(document.get("themes"), list):
        raise TokenError("themes.json must hold an object with a 'themes' array")
    entries = document["themes"]
    if not 1 <= len(entries) <= THEMES_MAX:
        raise TokenError("themes.json holds 1 to %d themes, not %d" % (THEMES_MAX, len(entries)))
    themes, seen = [], set()
    for index, entry in enumerate(entries):
        where = "themes.json theme %d" % (index + 1)
        if not isinstance(entry, dict):
            raise TokenError("%s is not an object" % where)
        theme_id, label, body = entry.get("id"), entry.get("label"), entry.get("body")
        if not isinstance(theme_id, str) or not THEME_ID_RE.match(theme_id):
            raise TokenError("%s: id is 1 to 31 of [a-z0-9-], got %r" % (where, theme_id))
        if theme_id in seen:
            raise TokenError("%s: id %r appears twice" % (where, theme_id))
        seen.add(theme_id)
        if (not isinstance(label, str) or not label or len(label.encode("utf-8")) > THEME_LABEL_MAX
                or any(ord(c) < 0x20 or ord(c) == 0x7f for c in label)):
            raise TokenError("%s (%s): label is 1 to %d bytes of text without control characters"
                             % (where, theme_id, THEME_LABEL_MAX))
        if not isinstance(body, list) or not 1 <= len(body) <= THEME_CLASSES_MAX:
            raise TokenError("%s (%s): body is an array of 1 to %d class names" % (where, theme_id, THEME_CLASSES_MAX))
        for name in body:
            if not isinstance(name, str) or not THEME_CLASS_RE.match(name) or name == "nui-shown":
                raise TokenError("%s (%s): %r is not a theme class" % (where, theme_id, name))
        if len(set(body)) != len(body):
            raise TokenError("%s (%s): a class appears twice in body" % (where, theme_id))
        skins = [name for name in body if name.startswith("skin-")]
        palettes = [name for name in body if name.startswith("theme-")]
        if len(skins) != 1 or len(palettes) != 1:
            raise TokenError("%s (%s): body needs exactly one skin-* and one theme-* class, got %s"
                             % (where, theme_id, ", ".join(body)))
        themes.append((theme_id, label, list(body)))
    if themes[0][0] != DEFAULT_THEME_ID:
        raise TokenError("themes.json: the first theme is the default and must be %r, not %r"
                         % (DEFAULT_THEME_ID, themes[0][0]))
    return themes


def theme_class(theme, prefix):
    """The one class of `theme` that starts with prefix ("skin-" or "theme-"),
    without the prefix."""
    return next(name for name in theme[2] if name.startswith(prefix))[len(prefix):]


def palette_order(themes):
    """Palette names in the order their first theme appears."""
    order = []
    for theme in themes:
        palette = theme_class(theme, "theme-")
        if palette not in order:
            order.append(palette)
    return order


def skin_order(themes):
    order = []
    for theme in themes:
        skin = theme_class(theme, "skin-")
        if skin not in order:
            order.append(skin)
    return order


# --- loading and validation --------------------------------------------------

def load_json(path):
    with open(path, encoding="utf-8") as handle:
        return json.load(handle)


def load(tokens_path=TOKENS_JSON, themes_path=THEMES_JSON):
    """(tokens, themes) after validation."""
    tokens = load_json(tokens_path)
    themes = validate_themes(load_json(themes_path))
    validate(tokens, themes)
    return tokens, themes


def palettes_of(tokens):
    return [name for name in tokens if name not in ("shared", SKINS)]


def validate(tokens, themes):
    if not isinstance(tokens, dict):
        raise TokenError("tokens.json must hold an object")
    if not isinstance(tokens.get("shared"), dict):
        raise TokenError("tokens.json needs an object 'shared'")
    skins = tokens.get(SKINS, {})
    if not isinstance(skins, dict) or not all(isinstance(values, dict) for values in skins.values()):
        raise TokenError("tokens.json 'skins' maps a skin name to an object of tokens")
    palettes = palettes_of(tokens)
    for name in palettes + list(skins):
        if not NAME_RE.match(name):
            raise TokenError("%r: section names are lowercase words joined by '-'" % name)
    for palette in palettes:
        if not isinstance(tokens[palette], dict):
            raise TokenError("palette %r must be an object" % palette)

    sections = [("shared", tokens["shared"])] + [(p, tokens[p]) for p in palettes]
    sections += [("skins.%s" % skin, values) for skin, values in skins.items()]
    for section, values in sections:
        for name, value in values.items():
            if not NAME_RE.match(name):
                raise TokenError("%s.%s: token names are lowercase words joined by '-'" % (section, name))
            if not isinstance(value, str) or not value.strip():
                raise TokenError("%s.%s: values are non-empty strings" % (section, name))

    # themes.json names the palettes and skins; neither side may name one the
    # other lacks.
    named_palettes = palette_order(themes)
    unnamed = [p for p in palettes if p not in named_palettes]
    if unnamed:
        raise TokenError("no theme in themes.json uses palette %s (class theme-%s)" % (unnamed[0], unnamed[0]))
    missing = [p for p in named_palettes if p not in palettes]
    if missing:
        raise TokenError("themes.json uses theme-%s, but tokens.json has no palette %r" % (missing[0], missing[0]))
    unused_skins = [s for s in skins if s not in skin_order(themes)]
    if unused_skins:
        raise TokenError("skins.%s: no theme in themes.json has the class skin-%s" % (unused_skins[0], unused_skins[0]))

    shared = tokens["shared"]
    missing = [name for name in REQUIRED_SHARED if name not in shared]
    if missing:
        raise TokenError("shared is missing: %s" % ", ".join(missing))
    for name, value in shared.items():
        check_shared_value(name, value)

    first = palettes[0] if palettes else None
    for palette in palettes:
        colors = tokens[palette]
        missing = [name for name in REQUIRED_COLORS if name not in colors]
        if missing:
            raise TokenError("%s is missing: %s" % (palette, ", ".join(missing)))
        for name, value in colors.items():
            parse_color(value)
            if name in shared:
                raise TokenError("%s.%s is also a shared token" % (palette, name))
        if set(colors) != set(tokens[first]):
            only = set(colors) ^ set(tokens[first])
            raise TokenError("every palette defines the same colors; %s and %s differ in: %s"
                             % (first, palette, ", ".join(sorted(only))))

    palette_names = set(tokens[first]) if first else set()
    for skin, values in skins.items():
        for name, value in values.items():
            where = "skins.%s.%s" % (skin, name)
            if name in shared:
                check_shared_value(name, value, where)
            elif not name.startswith(skin + "-"):
                raise TokenError("%s: a skin token overrides a shared one or is named %s-..." % (where, skin))
            elif not (COLOR_RE.match(value) or LENGTH_RE.match(value)):
                raise TokenError("%s: a skin's own token is a color or a dp length, got %r" % (where, value))
            if name in palette_names:
                raise TokenError("%s reuses a palette token name" % where)


def check_shared_value(name, value, where=None):
    """The prefix decides the kind, so a typo like '4px' or '120ms' fails here
    instead of in the client."""
    where = where or "shared.%s" % name
    if name.startswith(("space-", "radius-", "font-")) and name != "font-family":
        if not LENGTH_RE.match(value):
            raise TokenError("%s: lengths are in dp, got %r" % (where, value))
    elif name.startswith("dur-"):
        # RmlUi only reads "<float>s"; "120ms" is a syntax error and the declaration is dropped.
        if not DURATION_RE.match(value):
            raise TokenError("%s: durations are seconds like '0.12s', got %r" % (where, value))
    elif name.startswith("ease-"):
        if value not in RMLUI_TWEENS:
            raise TokenError("%s: %r is not an RmlUi tween (e.g. cubic-out)" % (where, value))
    elif name == "font-family":
        if any(c in value for c in ",;{}"):
            raise TokenError("%s: RCSS takes one family name, got %r" % (where, value))
    elif COLOR_RE.match(value):
        raise TokenError("%s: colors belong to the palettes" % where)


# --- outputs -----------------------------------------------------------------

def render_rcss(tokens, themes):
    lines = [
        "/* Generated from tokens.json by tools/nui_tokens.py. Do not edit by hand.",
        "   Regenerate from the nova-client repository root: %s" % COMMAND,
        "   Contrast of every text pair is checked there (WCAG AA). */",
        "",
        "body",
        "{",
    ]
    lines += ["\t--%s: %s;" % (name, value) for name, value in tokens["shared"].items()]
    lines.append("}")
    for index, palette in enumerate(palette_order(themes)):
        lines.append("")
        if index == 0:
            lines += [
                "/* Also the default: RmlUi computes styles once inside LoadDocument, before",
                "   the runtime can put a theme class on <body>. */",
                "body, body.theme-%s" % palette,
            ]
        else:
            lines.append("body.theme-%s" % palette)
        lines.append("{")
        lines += ["\t--%s: %s;" % (name, value) for name, value in tokens[palette].items()]
        lines.append("}")
    skins = tokens.get(SKINS, {})
    for skin in skin_order(themes):
        if not skins.get(skin):
            continue
        lines += [
            "",
            "/* Skin %s: overrides shared tokens and adds its own (%s-...) while a" % (skin, skin),
            "   theme of this skin is in use. */",
            "body.skin-%s" % skin,
            "{",
        ]
        lines += ["\t--%s: %s;" % (name, value) for name, value in skins[skin].items()]
        lines.append("}")
    return "\n".join(lines) + "\n"


def render_table(tokens, themes):
    palettes = palette_order(themes)
    first = palettes[0]
    rows = [TABLE_BEGIN, "",
            "| Token | %s |" % " | ".join(p.capitalize() for p in palettes),
            "|---|" + "---|" * len(palettes)]
    for name in tokens[first]:
        rows.append("| `--%s` | %s |" % (name, " | ".join("`%s`" % tokens[p][name] for p in palettes)))
    rows += ["", "| Token | Shared value |", "|---|---|"]
    for name, value in tokens["shared"].items():
        rows.append("| `--%s` | `%s` |" % (name, value))
    skins = tokens.get(SKINS, {})
    skin_rows = [(name, skin, value) for skin in skin_order(themes) for name, value in skins.get(skin, {}).items()]
    if skin_rows:
        rows += ["", "| Token | Skin | Value |", "|---|---|---|"]
        rows += ["| `--%s` | %s | `%s` |" % row for row in skin_rows]
    rows += ["", TABLE_END]
    return "\n".join(rows)


def splice_table(markdown, table):
    begin = markdown.find(TABLE_BEGIN)
    end = markdown.find(TABLE_END)
    if begin < 0 or end < begin:
        raise TokenError("docs/ui/AUTHORING.md needs the markers %r and %r" % (TABLE_BEGIN, TABLE_END))
    return markdown[:begin] + table + markdown[end + len(TABLE_END):]


def contrast_report(tokens, themes):
    """[(palette, fg, bg, ratio, minimum, purpose)] for every pair of every palette."""
    report = []
    for palette in palette_order(themes):
        colors = tokens[palette]
        for fg, bg, minimum, purpose in CONTRAST_PAIRS:
            ratio = contrast_ratio(parse_color(colors[fg]), parse_color(colors[bg]))
            report.append((palette, fg, bg, ratio, minimum, purpose))
    return report


def format_report(report):
    lines = []
    for palette, fg, bg, ratio, minimum, purpose in report:
        verdict = "ok  " if ratio >= minimum else "FAIL"
        lines.append("%s %-7s %-13s on %-15s %5.2f:1 (min %.1f) %s" % (verdict, palette, fg, bg, ratio, minimum, purpose))
    return "\n".join(lines)


def read_text(path):
    try:
        with open(path, encoding="utf-8", newline="") as handle:
            return handle.read()
    except FileNotFoundError:
        return None


def write_text(path, text):
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


def main(argv):
    check_only = "--check" in argv
    unknown = [arg for arg in argv if arg != "--check"]
    if unknown:
        print(__doc__.strip())
        return 2
    try:
        tokens, themes = load()
        rcss = render_rcss(tokens, themes)
        markdown = read_text(AUTHORING_MD)
        if markdown is None:
            raise TokenError("docs/ui/AUTHORING.md not found")
        docs = splice_table(markdown, render_table(tokens, themes))
        report = contrast_report(tokens, themes)
    except (TokenError, ValueError, OSError) as error:
        print("nui_tokens: %s" % error, file=sys.stderr)
        return 1

    print(format_report(report))
    failures = [row for row in report if row[3] < row[4]]
    outputs = ((TOKENS_RCSS, rcss), (AUTHORING_MD, docs))
    stale = [(path, text) for path, text in outputs if read_text(path) != text]
    for path, text in stale:
        name = os.path.relpath(path, REPO)
        if check_only:
            print("stale: %s (run %s)" % (name, COMMAND), file=sys.stderr)
        else:
            write_text(path, text)
            print("wrote %s" % name)
    if failures:
        print("%d contrast pair(s) below the minimum" % len(failures), file=sys.stderr)
    return 1 if failures or (check_only and stale) else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
