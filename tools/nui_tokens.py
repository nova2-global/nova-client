# --- colors ----------------------------------------------------------------

def parse_color(value):
    """#rrggbb or #rrggbbaa -> (r, g, b, a) as floats in 0..1."""
    if not COLOR_RE.match(value):
        raise TokenError("not a #rrggbb or #rrggbbaa color: %r" % value)
    digits = value[1:]
    channels = [int(digits[i:i + 2], 16) / 255.0 for i in range(0, len(digits), 2)]
    if len(channels) == 3:
        channels.append(1.0)
    return tuple(channels)


def composite(fg, bg):
    """Straight-alpha source over an opaque background."""
    alpha = fg[3]
    return tuple(fg[i] * alpha + bg[i] * (1.0 - alpha) for i in range(3)) + (1.0,)


def relative_luminance(color):
    def linear(c):
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = (linear(c) for c in color[:3])
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast_ratio(fg, bg):
    """WCAG contrast of fg drawn over an opaque bg."""
    if bg[3] < 1.0:
        raise TokenError("a contrast background must be opaque")
    fg = composite(fg, bg)
    lighter, darker = sorted((relative_luminance(fg), relative_luminance(bg)), reverse=True)
    return (lighter + 0.05) / (darker + 0.05)


def pair_contrast(colors, fg_name, bg_name):
    """Contrast for a token pair on the surface where that role is drawn.

    The modern selection and tooltip plates are deliberately translucent.
    Selection is painted inside a panel; tooltip plates are HUD overlays on
    the scene. Composite those backgrounds before applying the same WCAG
    ratio and threshold as every opaque pair.
    """
    fg, bg = parse_color(colors[fg_name]), parse_color(colors[bg_name])
    if bg[3] < 1.0:
        backdrop_name = "surface" if bg_name == "selection" else "scene"
        bg = composite(bg, parse_color(colors[backdrop_name]))
    return contrast_ratio(fg, bg)


# --- themes.json -------------------------------------------------------------

def validate_themes(document):
    """The rules of nui/theme/themes.json (the runtime's and lint's), plus the
    content convention: one skin-* and one theme-* class per theme. Returns
    the themes as [(id, label, [classes])] in menu order."""
    if not isinstance(document, dict) or not isinstance(document.get("themes"), list):
        raise TokenError("themes.json must hold an object with a 'themes' array")
    entries = document["themes"]
    if not 1 <= len(entries) <= THEMES_MAX:
        raise TokenError("themes.json holds 1 to %d themes, not %d" % (THEMES_MAX, len(entries)))
    themes, seen = [], set()
    for index, entry in enumerate(entries):
        where = "themes.json theme %d" % (index + 1)
        if not isinstance(entry, dict):
            raise TokenError("%s is not an object" % where)
        theme_id, label, body = entry.get("id"), entry.get("label"), entry.get("body")
        if not isinstance(theme_id, str) or not THEME_ID_RE.match(theme_id):
            raise TokenError("%s: id is 1 to 31 of [a-z0-9-], got %r" % (where, theme_id))
        if theme_id in seen:
            raise TokenError("%s: id %r appears twice" % (where, theme_id))
        seen.add(theme_id)
        if (not isinstance(label, str) or not label or len(label.encode("utf-8")) > THEME_LABEL_MAX
                or any(ord(c) < 0x20 or ord(c) == 0x7f for c in label)):
            raise TokenError("%s (%s): label is 1 to %d bytes of text without control characters"
                             % (where, theme_id, THEME_LABEL_MAX))
        if not isinstance(body, list) or not 1 <= len(body) <= THEME_CLASSES_MAX:
            raise TokenError("%s (%s): body is an array of 1 to %d class names" % (where, theme_id, THEME_CLASSES_MAX))
        for name in body:
            if not isinstance(name, str) or not THEME_CLASS_RE.match(name) or name == "nui-shown":
                raise TokenError("%s (%s): %r is not a theme class" % (where, theme_id, name))
        if len(set(body)) != len(body):
            raise TokenError("%s (%s): a class appears twice in body" % (where, theme_id))
        skins = [name for name in body if name.startswith("skin-")]
        palettes = [name for name in body if name.startswith("theme-")]
        if len(skins) != 1 or len(palettes) != 1:
            raise TokenError("%s (%s): body needs exactly one skin-* and one theme-* class, got %s"
                             % (where, theme_id, ", ".join(body)))
        chrome = entry.get("chrome", [])
        if (not isinstance(chrome, list) or len(chrome) > CHROME_MAX or len(set(chrome)) != len(chrome)
                or any(part not in CHROME_PARTS for part in chrome)):
            raise TokenError("%s (%s): chrome is 0 to %d of %s, none twice, got %r"
                             % (where, theme_id, CHROME_MAX, ", ".join(CHROME_PARTS), chrome))
        themes.append((theme_id, label, list(body)))
    if themes[0][0] != DEFAULT_THEME_ID:
        raise TokenError("themes.json: the first theme is the default and must be %r, not %r"
                         % (DEFAULT_THEME_ID, themes[0][0]))
    return themes


def theme_class(theme, prefix):
    """The one class of `theme` that starts with prefix ("skin-" or "theme-"),
    without the prefix."""
    return next(name for name in theme[2] if name.startswith(prefix))[len(prefix):]


def palette_order(themes):
    """Palette names in the order their first theme appears."""
    order = []
    for theme in themes:
        palette = theme_class(theme, "theme-")
        if palette not in order:
            order.append(palette)
    return order


def skin_order(themes):
    order = []
    for theme in themes:
        skin = theme_class(theme, "skin-")
        if skin not in order:
            order.append(skin)
    return order


# --- loading and validation --------------------------------------------------

def load_json(path):
    with open(path, encoding="utf-8") as handle:
        return json.load(handle)


def load(tokens_path=TOKENS_JSON, themes_path=THEMES_JSON):
    """(tokens, themes) after validation, the skins' own tokens included."""
    tokens = load_json(tokens_path)
    themes = validate_themes(load_json(themes_path))
    validate(tokens, themes)
    return tokens, themes


def load_skin_tokens(themes, skins_dir=SKINS_DIR):
    """{skin: its tokens.json} for every skin of themes.json whose folder
    holds one, in skin order."""
    out = {}
    for skin in skin_order(themes):
        path = os.path.join(skins_dir, skin, SKIN_TOKENS)
        if os.path.isfile(path):
            out[skin] = load_json(path)
    return out


def main_palettes(tokens, themes):
    """The palettes of the main tokens.json, in theme order."""
    return [palette for palette in palette_order(themes) if palette in tokens and palette not in RESERVED_SECTIONS]


def palettes_of(tokens):
    return [name for name in tokens if name not in RESERVED_SECTIONS]


def validate(tokens, themes, skin_tokens=None):
    """Raises TokenError for tokens.json, or a skin's tokens.json
    (skin_tokens: {skin: document}, by default the skin folders'), that
    breaks a rule."""
    skin_tokens = load_skin_tokens(themes) if skin_tokens is None else skin_tokens
    if not isinstance(tokens, dict):
        raise TokenError("tokens.json must hold an object")
    if not isinstance(tokens.get("shared"), dict):
        raise TokenError("tokens.json needs an object 'shared'")
    skins = tokens.get(SKINS, {})
    if not isinstance(skins, dict) or not all(isinstance(values, dict) for values in skins.values()):
        raise TokenError("tokens.json 'skins' maps a skin name to an object of tokens")
    palettes = palettes_of(tokens)
    for name in palettes + list(skins):
        if not NAME_RE.match(name):
            raise TokenError("%r: section names are lowercase words joined by '-'" % name)
    for palette in palettes:
        if not isinstance(tokens[palette], dict):
            raise TokenError("palette %r must be an object" % palette)

    sections = [("shared", tokens["shared"])] + [(p, tokens[p]) for p in palettes]
    sections += [("skins.%s" % skin, values) for skin, values in skins.items()]
    for section, values in sections:
        for name, value in values.items():
            if not NAME_RE.match(name):
                raise TokenError("%s.%s: token names are lowercase words joined by '-'" % (section, name))
            if not isinstance(value, str) or not value.strip():
                raise TokenError("%s.%s: values are non-empty strings" % (section, name))

    # themes.json names the palettes and skins; neither side may name one the
    # other lacks.
    named_palettes = palette_order(themes)
    unnamed = [p for p in palettes if p not in named_palettes]
    if unnamed:
        raise TokenError("no theme in themes.json uses palette %s (class theme-%s)" % (unnamed[0], unnamed[0]))
    skin_palettes = {name for doc in skin_tokens.values() if isinstance(doc, dict) for name in doc.get("palettes", {})}
    missing = [p for p in named_palettes if p not in palettes and p not in skin_palettes]
    if missing:
        raise TokenError("themes.json uses theme-%s, but tokens.json has no palette %r" % (missing[0], missing[0]))
    unused_skins = [s for s in skins if s not in skin_order(themes)]
    if unused_skins:
        raise TokenError("skins.%s: no theme in themes.json has the class skin-%s" % (unused_skins[0], unused_skins[0]))

    shared = tokens["shared"]
    missing = [name for name in REQUIRED_SHARED if name not in shared]
    if missing:
        raise TokenError("shared is missing: %s" % ", ".join(missing))
    for name, value in shared.items():
        check_shared_value(name, value)

    first = palettes[0] if palettes else None
    for palette in palettes:
        colors = tokens[palette]
        missing = [name for name in REQUIRED_COLORS if name not in colors]
        if missing:
            raise TokenError("%s is missing: %s" % (palette, ", ".join(missing)))
        for name, value in colors.items():
            parse_color(value)
            if name in shared:
                raise TokenError("%s.%s is also a shared token" % (palette, name))
        if set(colors) != set(tokens[first]):
            only = set(colors) ^ set(tokens[first])
            raise TokenError("every palette defines the same colors; %s and %s differ in: %s"
                             % (first, palette, ", ".join(sorted(only))))

    palette_names = set(tokens[first]) if first else set()
    for skin, values in skins.items():
        for name, value in values.items():
            where = "skins.%s.%s" % (skin, name)
            if name in shared:
                check_shared_value(name, value, where)
            elif not name.startswith(skin + "-"):
                raise TokenError("%s: a skin token overrides a shared one or is named %s-..." % (where, skin))
            elif not (COLOR_RE.match(value) or LENGTH_RE.match(value)):
                raise TokenError("%s: a skin's own token is a color or a dp length, got %r" % (where, value))
            if name in palette_names:
                raise TokenError("%s reuses a palette token name" % where)

    validate_slots(tokens.get(SLOTS, {}), tokens, palettes)
    for skin, doc in skin_tokens.items():
        validate_skin(skin, doc, tokens, themes)


def skin_colors(doc, palette):
    """A skin palette's colors with the skin's own color tokens (those its
    slots and pairs may name)."""
    colors = dict(doc["palettes"][palette])
    colors.update({name: value for name, value in doc.get("skin", {}).items() if COLOR_RE.match(value)})
    return colors


def validate_skin(skin, doc, tokens, themes):
    """The rules of nui/skins/<skin>/tokens.json (P13 spec 7.1)."""
    where = "skins/%s/%s" % (skin, SKIN_TOKENS)
    if not isinstance(doc, dict) or set(doc) - SKIN_KEYS:
        raise TokenError("%s: an object of %s" % (where, ", ".join(sorted(SKIN_KEYS - {"$comment"}))))
    palettes = doc.get("palettes", {})
    if not isinstance(palettes, dict) or not palettes:
        raise TokenError("%s: palettes maps a palette name to its colors" % where)
    reference = tokens[palettes_of(tokens)[0]]
    for name, colors in palettes.items():
        if not NAME_RE.match(name) or name in tokens:
            raise TokenError("%s: palette %r is not a new name of lowercase words joined by '-'" % (where, name))
        if not isinstance(colors, dict) or set(colors) != set(reference):
            only = set(colors) ^ set(reference) if isinstance(colors, dict) else set()
            raise TokenError("%s: palette %s holds every color the main palettes hold; differs in: %s"
                             % (where, name, ", ".join(sorted(only))))
        for token, value in colors.items():
            if not COLOR_RE.match(value):
                raise TokenError("%s: %s.%s is not a #rrggbb or #rrggbbaa color" % (where, name, token))
    shared = tokens["shared"]
    for name, value in doc.get("skin", {}).items():
        at = "%s: skin.%s" % (where, name)
        if not NAME_RE.match(name) or not isinstance(value, str):
            raise TokenError("%s: token names are lowercase words joined by '-', values strings" % at)
        if name in shared:
            check_shared_value(name, value, at)
        elif not name.startswith(skin + "-"):
            raise TokenError("%s: a skin token overrides a shared one or is named %s-..." % (at, skin))
        elif not (COLOR_RE.match(value) or LENGTH_RE.match(value)):
            raise TokenError("%s: a skin's own token is a color or a dp length, got %r" % (at, value))
    expected = {theme[0]: theme_class(theme, "theme-") for theme in themes
                if theme_class(theme, "skin-") == skin and theme_class(theme, "theme-") in palettes}
    if doc.get("themes", {}) != expected:
        raise TokenError("%s: themes must be %s, the themes of themes.json that use its palettes" % (where, json.dumps(expected)))
    slots = doc.get(SLOTS, {})
    for palette in slots:
        if palette != "$comment" and palette not in palettes:
            raise TokenError("%s: slots.%s names no palette of the skin" % (where, palette))
    validate_slots(slots, {name: skin_colors(doc, name) for name in palettes}, list(palettes))
    for pair in doc.get("pairs", []):
        if (not isinstance(pair, list) or len(pair) != 3 or not isinstance(pair[2], (int, float))
                or any(pair[i] not in skin_colors(doc, name) for i in (0, 1) for name in palettes)):
            raise TokenError("%s: a pair is [fg, bg, minimum ratio] of colors its palettes hold, not %r" % (where, pair))


def validate_slots(slots, tokens, palettes):
    """slots: {"$comment"?, <palette>: [slot, ...]}, each slot as
    tools/nui_palette.py and Core/Palette.h parse it; its rules name colors of
    its palette."""
    if not isinstance(slots, dict):
        raise TokenError("tokens.json 'slots' maps a palette to its list of color slots")
    for palette, entries in slots.items():
        if palette == "$comment":
            continue
        if palette not in palettes:
            raise TokenError("slots.%s: no palette of that name" % palette)
        if not isinstance(entries, list) or not entries:
            raise TokenError("slots.%s is a non-empty list of slots" % palette)
        names = [entry.get("slot") for entry in entries if isinstance(entry, dict)]
        if len(names) != len(set(names)):
            raise TokenError("slots.%s: a slot is listed twice" % palette)
        parsed = {"tokens": {name: nui_palette.parse_color(value) for name, value in tokens[palette].items()}}
        for entry in entries:
            try:
                nui_palette._parse_slot(entry, parsed)
            except nui_palette.PaletteError as error:
                raise TokenError("slots.%s: %s" % (palette, error))


def check_shared_value(name, value, where=None):
    """The prefix decides the kind, so a typo like '4px' or '120ms' fails here
    instead of in the client."""
    where = where or "shared.%s" % name
    if name.startswith(("space-", "radius-", "font-")) and name != "font-family":
        if not LENGTH_RE.match(value):
            raise TokenError("%s: lengths are in dp, got %r" % (where, value))
    elif name.startswith("dur-"):
        # RmlUi only reads "<float>s"; "120ms" is a syntax error and the declaration is dropped.
        if not DURATION_RE.match(value):
            raise TokenError("%s: durations are seconds like '0.12s', got %r" % (where, value))
    elif name.startswith("ease-"):
        if value not in RMLUI_TWEENS:
            raise TokenError("%s: %r is not an RmlUi tween (e.g. cubic-out)" % (where, value))
    elif name == "font-family":
        if any(c in value for c in ",;{}"):
            raise TokenError("%s: RCSS takes one family name, got %r" % (where, value))
    elif name in FILTER_TOKENS:
        if not FILTER_RE.match(value.strip()):
            raise TokenError("%s: a filter list (blur(6dp), ...) or none, got %r" % (where, value))
    elif COLOR_RE.match(value):
        raise TokenError("%s: colors belong to the palettes" % where)


# --- outputs -----------------------------------------------------------------

def render_rcss(tokens, themes):
    lines = [
        "/* Generated from tokens.json by tools/nui_tokens.py. Do not edit by hand.",
        "   Regenerate from the nova-client repository root: %s" % COMMAND,
        "   Contrast of every text pair is checked there (WCAG AA). */",
        "",
        "body",
        "{",
    ]
    lines += ["\t--%s: %s;" % (name, value) for name, value in tokens["shared"].items()]
    lines.append("}")
    for index, palette in enumerate(main_palettes(tokens, themes)):
        lines.append("")
        if index == 0:
            lines += [
                "/* Also the default: RmlUi computes styles once inside LoadDocument, before",
                "   the runtime can put a theme class on <body>. */",
                "body, body.theme-%s" % palette,
            ]
        else:
            lines.append("body.theme-%s" % palette)
        lines.append("{")
        lines += ["\t--%s: %s;" % (name, value) for name, value in tokens[palette].items()]
        lines.append("}")
    skins = tokens.get(SKINS, {})
    for skin in skin_order(themes):
        if not skins.get(skin):
            continue
        lines += [
            "",
            "/* Skin %s: overrides shared tokens and adds its own (%s-...) while a" % (skin, skin),
            "   theme of this skin is in use. */",
            "body.skin-%s" % skin,
            "{",
        ]
        lines += ["\t--%s: %s;" % (name, value) for name, value in skins[skin].items()]
        lines.append("}")
    return "\n".join(lines) + "\n"


def render_table(tokens, themes):
    palettes = main_palettes(tokens, themes)
    first = palettes[0]
    rows = [TABLE_BEGIN, "",
            "| Token | %s |" % " | ".join(p.capitalize() for p in palettes),
            "|---|" + "---|" * len(palettes)]
    for name in tokens[first]:
        rows.append("| `--%s` | %s |" % (name, " | ".join("`%s`" % tokens[p][name] for p in palettes)))
    rows += ["", "| Token | Shared value |", "|---|---|"]
    for name, value in tokens["shared"].items():
        rows.append("| `--%s` | `%s` |" % (name, value))
    skins = tokens.get(SKINS, {})
    skin_rows = [(name, skin, value) for skin in skin_order(themes) for name, value in skins.get(skin, {}).items()]
    if skin_rows:
        rows += ["", "| Token | Skin | Value |", "|---|---|---|"]
        rows += ["| `--%s` | %s | `%s` |" % row for row in skin_rows]
    rows += ["", TABLE_END]
    return "\n".join(rows)


def palette_tone(colors):
    """dark or light: the palette's surface luminance below or above 0.18."""
    return "dark" if relative_luminance(parse_color(colors["surface"])) < 0.18 else "light"


def render_colors(tokens, themes, comment=None, palettes=None, pairs=None, theme_ids=None):
    """colors.json (P13 spec 5.2): the contrast pairs, every palette that
    offers color slots with all its colors and its slots, and the themes of
    those palettes. One entry per line, so a change reads as a line."""
    slots = tokens.get(SLOTS, {})
    names = [p for p in (palettes if palettes is not None else palette_order(themes)) if p in slots]
    pairs = pairs if pairs is not None else [[fg, bg, minimum] for fg, bg, minimum, _ in CONTRAST_PAIRS if bg not in OVERLAY_PLATES]
    theme_map = [(theme[0], theme_class(theme, "theme-")) for theme in themes
                 if theme_class(theme, "theme-") in names and (theme_ids is None or theme[0] in theme_ids)]
    dump = lambda value: json.dumps(value, ensure_ascii=False)
    lines = ["{",
             '	"$comment": %s,' % dump(comment or "Generated from tokens.json by %s. Do not edit by hand. The palettes that "
                                                   "offer player colors, their slots and the contrast pairs the resolve keeps "
                                                   "(docs/ui/AUTHORING.md \"Player colors\")." % COMMAND),
             '	"version": 1,',
             '	"pairs": [']
    lines += ["		%s%s" % (dump(pair), "," if i < len(pairs) - 1 else "") for i, pair in enumerate(pairs)]
    lines += ["	],", '	"palettes": {']
    for index, name in enumerate(names):
        colors = tokens[name]
        lines += ['		%s: {' % dump(name), '			"tone": %s,' % dump(palette_tone(colors)), '			"tokens": {']
        items = list(colors.items())
        lines += ["				%s: %s%s" % (dump(k), dump(v.lower()), "," if i < len(items) - 1 else "") for i, (k, v) in enumerate(items)]
        lines += ["			},", '			"slots": [']
        lines += ["				%s%s" % (dump(slot), "," if i < len(slots[name]) - 1 else "") for i, slot in enumerate(slots[name])]
        lines += ["			]", "		}%s" % ("," if index < len(names) - 1 else "")]
    lines += ["	},", '	"themes": {']
    lines += ["		%s: %s%s" % (dump(theme_id), dump(name), "," if i < len(theme_map) - 1 else "") for i, (theme_id, name) in enumerate(theme_map)]
    lines += ["	}", "}"]
    return "\n".join(lines) + "\n"


def swatch_failures(documents):
    """The swatch check (P13 spec 5.2): resolve every swatch of every slot of
    every theme the colors.json documents offer, alone and with the lowest
    opacity, and list (theme, values, failed pairs) for each that leaves a
    pair failed."""
    data = {"palettes": {}, "themes": {}}
    for document in documents:
        nui_palette.parse_colors(document, data)
    failures = []
    for theme_id in sorted(data["themes"]):
        slots = nui_palette.slots_of_theme(data, theme_id)
        opacity = next((s for s in slots if s["slot"] == nui_palette.OPACITY and s["kind"] == "percent"), None)
        for slot in slots:
            values = slot["swatches"] if slot["kind"] == "color" else [str(slot["min"])]
            for value in values:
                cases = [{slot["slot"]: value}]
                if opacity is not None and slot is not opacity:
                    cases.append({slot["slot"]: value, opacity["slot"]: str(opacity["min"])})
                for case in cases:
                    failed = nui_palette.resolve(data, theme_id, case)["failed"]
                    if failed:
                        failures.append((theme_id, case, failed))
    return failures


# --- a skin's own tokens (nui/skins/<skin>/tokens.json) --------------------------

def skin_paths(skin, skins_dir=SKINS_DIR):
    folder = os.path.join(skins_dir, skin)
    return {"rcss": os.path.join(folder, "%s-tokens.rcss" % skin), "colors": os.path.join(folder, "colors.json"),
            "readme": os.path.join(folder, "README.md")}


def render_skin_rcss(skin, doc):
    """<skin>-tokens.rcss: each palette under body.skin-<skin>.theme-<palette>,
    the skin's own tokens under body.skin-<skin> (selectors start with the
    skin's class, lint NUI014)."""
    lines = ["/* Generated from nui/skins/%s/tokens.json by tools/nui_tokens.py. Do not edit by hand." % skin,
             "   Regenerate from the nova-client repository root: %s" % COMMAND,
             "   Contrast of every text pair is checked there (WCAG AA). */"]
    for palette, colors in doc["palettes"].items():
        lines += ["", "body.skin-%s.theme-%s" % (skin, palette), "{"]
        lines += ["\t--%s: %s;" % (name, value) for name, value in colors.items()]
        lines.append("}")
    if doc.get("skin"):
        lines += ["", "/* The skin's own tokens (%s-...) and the shared ones it overrides. */" % skin, "body.skin-%s" % skin, "{"]
        lines += ["\t--%s: %s;" % (name, value) for name, value in doc["skin"].items()]
        lines.append("}")
    return "\n".join(lines) + "\n"


def render_skin_colors(skin, doc, themes):
    """The skin's colors.json, or None when it offers no slots."""
    slots = {name: value for name, value in doc.get(SLOTS, {}).items() if name != "$comment"}
    if not slots:
        return None
    merged = {name: skin_colors(doc, name) for name in doc["palettes"]}
    merged[SLOTS] = slots
    pairs = [[fg, bg, minimum] for fg, bg, minimum, _ in CONTRAST_PAIRS] + [list(pair) for pair in doc.get("pairs", [])]
    comment = ("Generated from nui/skins/%s/tokens.json by %s. Do not edit by hand. The %s skin's palettes that offer "
               "player colors (docs/ui/AUTHORING.md \"Player colors\")." % (skin, COMMAND, skin))
    return render_colors(merged, themes, comment=comment, palettes=list(doc["palettes"]), pairs=pairs,
                         theme_ids=set(doc.get("themes", {})))


def render_skin_table(skin, doc):
    palettes = list(doc["palettes"])
    rows = [SKIN_TABLE_BEGIN, "", "| Token | %s |" % " | ".join(palettes), "|---|" + "---|" * len(palettes)]
    for name in doc["palettes"][palettes[0]]:
        rows.append("| `--%s` | %s |" % (name, " | ".join("`%s`" % doc["palettes"][p][name] for p in palettes)))
    if doc.get("skin"):
        rows += ["", "| Skin token | Value |", "|---|---|"]
        rows += ["| `--%s` | `%s` |" % item for item in doc["skin"].items()]
    rows += ["", SKIN_TABLE_END]
    return "\n".join(rows)


def splice_skin_table(markdown, table, where):
    begin, end = markdown.find(SKIN_TABLE_BEGIN), markdown.find(SKIN_TABLE_END)
    if begin < 0 or end < begin:
        raise TokenError("%s needs the markers %r and %r" % (where, SKIN_TABLE_BEGIN, SKIN_TABLE_END))
    return markdown[:begin] + table + markdown[end + len(SKIN_TABLE_END):]


def skin_contrast_report(skin, doc):
    """[(palette, fg, bg, ratio, minimum, purpose)] for every pair of every
    palette of the skin, its own pairs included."""
    pairs = list(CONTRAST_PAIRS) + [(fg, bg, minimum, "the %s skin's pair" % skin) for fg, bg, minimum in doc.get("pairs", [])]
    report = []
    for palette in doc["palettes"]:
        colors = skin_colors(doc, palette)
        for fg, bg, minimum, purpose in pairs:
            report.append((palette, fg, bg, pair_contrast(colors, fg, bg), minimum, purpose))
    return report


def skin_outputs(themes, skins_dir=SKINS_DIR):
    """[(path, text)] of every skin's generated files, and its contrast rows."""
    outputs, report = [], []
    for skin, doc in load_skin_tokens(themes, skins_dir).items():
        paths = skin_paths(skin, skins_dir)
        outputs.append((paths["rcss"], render_skin_rcss(skin, doc)))
        colors = render_skin_colors(skin, doc, themes)
        if colors is not None:
            outputs.append((paths["colors"], colors))
        readme = read_text(paths["readme"])
        if readme is None:
            raise TokenError("skins/%s/README.md not found" % skin)
        outputs.append((paths["readme"], splice_skin_table(readme, render_skin_table(skin, doc), "skins/%s/README.md" % skin)))
        report += skin_contrast_report(skin, doc)
    return outputs, report


def splice_table(markdown, table):
    begin = markdown.find(TABLE_BEGIN)
    end = markdown.find(TABLE_END)
    if begin < 0 or end < begin:
        raise TokenError("docs/ui/AUTHORING.md needs the markers %r and %r" % (TABLE_BEGIN, TABLE_END))
    return markdown[:begin] + table + markdown[end + len(TABLE_END):]


def contrast_report(tokens, themes):
    """[(palette, fg, bg, ratio, minimum, purpose)] for every pair of every palette."""
    report = []
    for palette in main_palettes(tokens, themes):
        colors = tokens[palette]
        for fg, bg, minimum, purpose in CONTRAST_PAIRS:
            ratio = pair_contrast(colors, fg, bg)
            report.append((palette, fg, bg, ratio, minimum, purpose))
    return report


def format_report(report):
    lines = []
    for palette, fg, bg, ratio, minimum, purpose in report:
        verdict = "ok  " if ratio >= minimum else "FAIL"
        lines.append("%s %-7s %-13s on %-15s %5.2f:1 (min %.1f) %s" % (verdict, palette, fg, bg, ratio, minimum, purpose))
    return "\n".join(lines)


def read_text(path):
    try:
        with open(path, encoding="utf-8", newline="") as handle:
            return handle.read()
    except FileNotFoundError:
        return None


def write_text(path, text):
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


def main(argv):
    check_only = "--check" in argv
    unknown = [arg for arg in argv if arg != "--check"]
    if unknown:
        print(__doc__.strip())
        return 2
    try:
        tokens, themes = load()
        rcss = render_rcss(tokens, themes)
        colors = render_colors(tokens, themes)
        skin_files, skin_report = skin_outputs(themes)
        swatches = swatch_failures([colors] + [text for path, text in skin_files if path.endswith("colors.json")])
        markdown = read_text(AUTHORING_MD)
        if markdown is None:
            raise TokenError("docs/ui/AUTHORING.md not found")
        docs = splice_table(markdown, render_table(tokens, themes))
        report = contrast_report(tokens, themes) + skin_report
    except (TokenError, nui_palette.PaletteError, ValueError, OSError) as error:
        print("nui_tokens: %s" % error, file=sys.stderr)
        return 1

    print(format_report(report))
    failures = [row for row in report if row[3] < row[4]]
    for theme_id, case, failed in swatches:
        print("FAIL swatch %s %s leaves %s" % (theme_id, ",".join("%s=%s" % kv for kv in sorted(case.items())),
                                               ", ".join("%s on %s" % tuple(pair) for pair in failed)), file=sys.stderr)
    outputs = [(TOKENS_RCSS, rcss), (COLORS_JSON, colors), (AUTHORING_MD, docs)] + skin_files
    stale = [(path, text) for path, text in outputs if read_text(path) != text]
    for path, text in stale:
        name = os.path.relpath(path, REPO)
        if check_only:
            print("stale: %s (run %s)" % (name, COMMAND), file=sys.stderr)
        else:
            write_text(path, text)
            print("wrote %s" % name)
    if failures:
        print("%d contrast pair(s) below the minimum" % len(failures), file=sys.stderr)
    if swatches:
        print("%d swatch case(s) leave a contrast pair failed" % len(swatches), file=sys.stderr)
    return 1 if failures or swatches or (check_only and stale) else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
